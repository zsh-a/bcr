import { parseArgs } from 'node:util';
export function parseCli(args = process.argv.slice(2)) {
  return parseArgs({
    args: args,
    allowPositionals: true,
    strict: true,
    options: {
      root: { type: 'string' },
      title: { type: 'string' },
      'no-install': { type: 'boolean' },
      help: { type: 'boolean', short: 'h' },
      target: { type: 'string' },
      task: { type: 'string' },
      segment: { type: 'string' },
      kind: { type: 'string' },
      status: { type: 'string' },
      note: { type: 'string' },
      evidence: { type: 'string' },
      reviewer: { type: 'string' },
      'reviewer-type': { type: 'string' },
      scope: { type: 'string' },
      output: { type: 'string' },
      frame: { type: 'string' },
      from: { type: 'string' },
      to: { type: 'string' },
      cq: { type: 'string' },
      scale: { type: 'string' },
      concurrency: { type: 'string' },
      encoder: { type: 'string' },
      'cpu-reason': { type: 'string' },
      check: { type: 'boolean' },
      plan: { type: 'boolean' },
      'logic-only': { type: 'boolean' },
      'baseline-directory': { type: 'string' },
      snapshot: { type: 'string' },
      'require-raw': { type: 'boolean' },
      force: { type: 'boolean' },
      apply: { type: 'boolean' },
      'budget-gib': { type: 'string' },
      'from-dir': { type: 'string' },
      models: { type: 'boolean' },
      json: { type: 'boolean' },
      summary: { type: 'boolean' },
    },
  });
}
