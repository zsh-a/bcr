type EventSeed = Omit<MacroEvent, "precision" | "sources"> & {
  source: [string, string];
  supportingSources?: MacroEvent["sources"];
};
const event = ({ source, supportingSources = [], ...seed }: EventSeed): MacroEvent => ({
  ...seed,
  precision: seed.start.length === 4 ? "year" : seed.start.length === 7 ? "month" : "day",
  sources: [{ title: source[0], url: source[1] }, ...supportingSources],
});

