export interface MacroEvent {
  id: string;
  title: string;
  start: string;
  end?: string;
  precision: "day" | "month" | "year";
  category: MacroEventCategory;
  /** ISO3 economies involved; an empty array denotes a global context event. */
  countries: string[];
  summary: string;
  /** An observation prompt, not an estimate of the event's causal effect. */
  mechanism: string;
  sources: { title: string; url: string }[];
}

