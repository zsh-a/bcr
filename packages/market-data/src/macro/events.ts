/** Include global context and any overlapping involved economy; retain input order. */
export function filterMacroEvents(
  events: readonly MacroEvent[],
  countries: string[],
  range: [number, number],
  category: MacroEventCategory | "all",
): MacroEvent[] {
  if (!Number.isFinite(range[0]) || !Number.isFinite(range[1]) || range[0] > range[1]) return [];
  const selected = new Set(countries);
  return events.filter((item) => {
    const startYear = Number(item.start.slice(0, 4));
    const endYear = Number((item.end ?? item.start).slice(0, 4));
    return (
      startYear <= range[1] &&
      endYear >= range[0] &&
      (category === "all" || item.category === category) &&
      (selected.size === 0 ||
        item.countries.length === 0 ||
        item.countries.some((id) => selected.has(id)))
    );
  });
}
